CONTENT_H = 29.7 - 5.0
used = 0.0
pages = 1  # 封面已占 1 页


def _add(cm):
    global used, pages
    if used + cm > CONTENT_H:
        pages += 1
        used = 0.0
    used += cm


def h1(text):
    doc.heading(text, 1)
    _add(1.3)


def h2(text):
    doc.heading(text, 2)
    _add(1.0)


def p(text):
    doc.body(text)
    # 12pt、1.5 倍、首行缩进，按约 38 字一行估算
    lines = max(1, (len(text) + 8) // 34)
    _add(0.64 * lines + 0.15)


def fig(name, caption, wide=False):
    path = SHOT / name
    im = Image.open(path)
    width = 14.8 if wide else 6.8
    height = width * im.size[1] / im.size[0]
    if height > CONTENT_H - 1.2:
        width = width * (CONTENT_H - 1.2) / height
        height = CONTENT_H - 1.2
    doc.image(str(path), caption=caption, width_cm=width)
    _add(height + 0.9)


def break_page():
    global used, pages
    doc.page_break()
    pages += 1
    used = 0.0


